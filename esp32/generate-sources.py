"""Prepare the ESP32 build: run the generate step of the make build for
TARGET=ESP32 (headers, resources, translations) and write the source
lists and flags make would use to output/ESP32/Sources.cmake.

Usage: esp32/generate-sources.py [-j N]

Needs the host tools of the normal build (make, perl, a C++ compiler,
ImageMagick, rsvg-convert, sox, xsltproc, gettext).
"""

import argparse
import os
import platform
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, 'output', 'ESP32', 'Sources.cmake')

# Generated files that are not part of "make generate"
EXTRA_GENERATED = [
    'output/ESP32/resources.c',
    'output/ESP32/include/MakeResource.hpp',
    'output/ESP32/include/ResourceLookup_entries.cpp',
]

# Libraries provided by the ESP32 build itself (esp32/Sources.cmake or
# ESP-IDF components); make only knows their flags for the host
EXTERNAL_LIBRARIES = {
    'CARES', 'FREETYPE', 'LIBJPEG', 'LIBLUA', 'LIBPNG', 'ZLIB',
}

# Sources the ESP32 build leaves out
EXCLUDED_SOURCES = set()


def make_args():
    args = ['make', '-s', 'TARGET=ESP32', 'USE_CCACHE=n']
    if platform.system() == 'Darwin':
        # host tools are built with the system compiler
        args.append('CLANG=y')
    return args


def generate(jobs):
    subprocess.run(make_args() + [f'-j{jobs}', 'generate'] + EXTRA_GENERATED,
                   cwd=ROOT, check=True)


def print_variables(names):
    """Return the values of make variables, as lists of words."""
    with tempfile.NamedTemporaryFile('w', suffix='.mk', delete=False) as f:
        f.write('print-%:\n\t@echo "$*=$($*)"\n')
        print_mk = f.name
    try:
        result = subprocess.run(
            make_args() + ['-f', 'Makefile', '-f', print_mk] +
            [f'print-{name}' for name in names],
            cwd=ROOT, check=True, capture_output=True, text=True)
    finally:
        os.unlink(print_mk)

    values = {}
    for line in result.stdout.splitlines():
        name, sep, value = line.partition('=')
        if sep and name in names:
            values[name] = value.split()
    return values


def collect_libraries():
    """All libraries the program depends on, directly or indirectly."""
    libraries = []
    pending = print_variables(['XCSOAR_DEPENDS'])['XCSOAR_DEPENDS']
    while pending:
        pending = [d for d in pending if d not in libraries]
        if not pending:
            break
        libraries += pending
        depends = print_variables([f'{d}_DEPENDS' for d in pending])
        pending = [d for values in depends.values() for d in values]
    return libraries


def normalise(path):
    path = os.path.normpath(path)
    return os.path.relpath(path, ROOT) if os.path.isabs(path) else path


def main():
    parser = argparse.ArgumentParser()
    # make 3.81 (macOS) has been seen to hang with many jobs
    parser.add_argument('-j', type=int, default=1)
    args = parser.parse_args()

    generate(args.j)

    libraries = [lib for lib in collect_libraries()
                 if lib not in EXTERNAL_LIBRARIES]
    names = ['XCSOAR_SOURCES', 'RESOURCES_SOURCES', 'TARGET_CPPFLAGS',
             'INCLUDES', 'VERSION_CPPFLAGS']
    for lib in libraries:
        names += [f'{lib}_SOURCES', f'{lib}_CPPFLAGS',
                  f'{lib}_CPPFLAGS_INTERNAL']
    values = print_variables(names)

    sources = []
    for name in ['XCSOAR_SOURCES', 'RESOURCES_SOURCES'] + \
            [f'{lib}_SOURCES' for lib in libraries]:
        for source in values.get(name, []):
            source = normalise(source)
            if source not in sources and source not in EXCLUDED_SOURCES:
                sources.append(source)

    defines = []
    include_dirs = []
    flags = values.get('TARGET_CPPFLAGS', []) + values.get('INCLUDES', []) + \
        values.get('VERSION_CPPFLAGS', [])
    for lib in libraries:
        flags += values.get(f'{lib}_CPPFLAGS', [])
        flags += values.get(f'{lib}_CPPFLAGS_INTERNAL', [])
    for flag in flags:
        if flag.startswith('-D'):
            define = flag[2:]
            # a host debugging aid
            if define != '_GLIBCXX_ASSERTIONS' and define not in defines:
                defines.append(define)
        elif flag.startswith('-I'):
            include_dir = normalise(flag[2:])
            if include_dir not in include_dirs:
                include_dirs.append(include_dir)
        # -isystem flags point at host libraries

    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT + '.tmp', 'w') as f:
        f.write('# Generated by esp32/generate-sources.py from the make '
                'build (TARGET=ESP32)\n\n')
        for name, items in (('XCSOAR_APP_SOURCES', sources),
                            ('XCSOAR_APP_DEFINES', defines),
                            ('XCSOAR_APP_INCLUDE_DIRS', include_dirs)):
            f.write(f'set({name}\n')
            for item in items:
                quoted = item.replace('\\', '\\\\').replace('"', '\\"')
                f.write(f'  "{quoted}"\n')
            f.write(')\n\n')
    os.replace(OUTPUT + '.tmp', OUTPUT)
    print(f'{OUTPUT}: {len(sources)} sources, {len(libraries)} libraries')


if __name__ == '__main__':
    sys.exit(main())
